#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = ["pillow>=10"]
# ///
"""Build tiny country flag bitmaps (RGB332) for aircraft route tags.

Source: flagcdn.com PNG flags (public domain). Each ISO 3166-1 alpha-2 flag is
downscaled to FLAG_W x FLAG_H and stored as one RGB332 byte per pixel, the
same format as the radar frame sprite, so it blits without conversion.

  uv run scripts/build_flags.py [--cache DIR]
"""

from __future__ import annotations

import argparse
import concurrent.futures
import io
import json
import urllib.request
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT_H = ROOT / "include" / "data" / "flags.h"
OUT_CPP = ROOT / "src" / "data" / "flags_data.cpp"

CODES_URL = "https://flagcdn.com/en/codes.json"
# 40 px wide source: enough detail for a clean downscale.
FLAG_URL = "https://flagcdn.com/w40/{code}.png"

FLAG_W = 15
FLAG_H = 10
# Colour snapping: at most this many colours, each covering MIN_SHARE of the flag.
PALETTE_COLORS = 6
MIN_SHARE = 0.03


def fetch(url: str, cache: Path | None, name: str) -> bytes:
    if cache is not None:
        path = cache / name
        if path.exists():
            return path.read_bytes()
    req = urllib.request.Request(url, headers={"User-Agent": "plane-radar-build"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        data = resp.read()
    if cache is not None:
        cache.mkdir(parents=True, exist_ok=True)
        (cache / name).write_bytes(data)
    return data


def srgb_to_linear(c: int) -> float:
    v = c / 255.0
    return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4


def nearest_level(c: int, levels: int) -> int:
    # Nearest in linear light: plain sRGB rounding lifts small amounts of a
    # channel to the first level, which turns flag reds pink (blue 46 -> 85)
    # and washes out saturated colours on this tiny palette.
    target = srgb_to_linear(c)
    steps = [srgb_to_linear(round(i * 255 / (levels - 1))) for i in range(levels)]
    return min(range(levels), key=lambda i: abs(steps[i] - target))


def to_rgb332(r: int, g: int, b: int) -> int:
    return (nearest_level(r, 8) << 5) | (nearest_level(g, 8) << 2) | nearest_level(b, 4)


def render_flag(png: bytes) -> list[int]:
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    # Flatten any transparency (e.g. Nepal) onto black, the tag background.
    bg = Image.new("RGBA", img.size, (0, 0, 0, 255))
    img = Image.alpha_composite(bg, img).convert("RGB")
    small = img.resize((FLAG_W, FLAG_H), Image.BOX)
    # Snap every pixel to one of the flag's own main colours: at this size a
    # plain downscale blends neighbours (Denmark's white cross turns pink).
    palette = flag_palette(img)
    out = []
    for y in range(FLAG_H):
        for x in range(FLAG_W):
            px = small.getpixel((x, y))
            best = min(palette, key=lambda c: sum((a - b) ** 2 for a, b in zip(c, px)))
            out.append(to_rgb332(*best))
    return out


def flag_palette(img: Image.Image) -> list[tuple[int, int, int]]:
    """The flag's dominant colours (each covering at least MIN_SHARE)."""
    q = img.quantize(colors=PALETTE_COLORS, method=Image.Quantize.MEDIANCUT)
    pal = q.getpalette()
    total = img.width * img.height
    colors = []
    for count, idx in sorted(q.getcolors(), reverse=True):
        if count / total >= MIN_SHARE or not colors:
            colors.append(tuple(pal[idx * 3:idx * 3 + 3]))
    return colors


def build(cache: Path | None) -> list[tuple[str, list[int]]]:
    codes = json.loads(fetch(CODES_URL, cache, "codes.json"))
    # Only country codes; skip subdivisions like "gb-eng" and groups like "eu".
    countries = sorted(c for c in codes if len(c) == 2 and c not in ("eu", "un"))

    def one(code: str) -> tuple[str, list[int]]:
        return code, render_flag(fetch(FLAG_URL.format(code=code), cache, f"{code}.png"))

    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
        return sorted(pool.map(one, countries))


def render_header(count: int) -> str:
    return "\n".join([
        "// Generated by scripts/build_flags.py — do not edit.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace data::flags {",
        "",
        f"constexpr int kFlagW = {FLAG_W};",
        f"constexpr int kFlagH = {FLAG_H};",
        "",
        "struct Flag {",
        "  char cc[3];  // ISO 3166-1 alpha-2, upper case",
        "  uint8_t px[kFlagW * kFlagH];  // RGB332, row-major",
        "};",
        "",
        f"constexpr size_t kFlagCount = {count};",
        "",
        "/** Sorted by cc. */",
        "extern const Flag kFlags[];",
        "",
        "}  // namespace data::flags",
        "",
    ])


def render_cpp(flags: list[tuple[str, list[int]]]) -> str:
    lines = [
        "// Generated by scripts/build_flags.py — do not edit.",
        "// Flags: flagcdn.com (public domain).",
        '#include "data/flags.h"',
        "",
        "namespace data::flags {",
        "",
        "const Flag kFlags[] = {",
    ]
    for code, px in flags:
        body = ",".join(str(p) for p in px)
        lines.append(f'  {{"{code.upper()}", {{{body}}}}},')
    lines += ["};", "", "}  // namespace data::flags", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--cache", type=Path, help="reuse/save downloaded flags here")
    args = ap.parse_args()

    flags = build(args.cache)
    OUT_H.parent.mkdir(parents=True, exist_ok=True)
    OUT_CPP.parent.mkdir(parents=True, exist_ok=True)
    OUT_H.write_text(render_header(len(flags)), encoding="utf-8")
    OUT_CPP.write_text(render_cpp(flags), encoding="utf-8")
    kb = len(flags) * (3 + FLAG_W * FLAG_H) / 1024
    print(f"wrote {OUT_H.name} + {OUT_CPP.name}: {len(flags)} flags "
          f"({FLAG_W}x{FLAG_H} RGB332), ~{kb:.0f} KB flash")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
